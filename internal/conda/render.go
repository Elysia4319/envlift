// 基础 pip 包由环境创建过程自带；默认不进入恢复清单，避免把工具链版本钉死。
var pipBootstrap = map[string]bool{
	"pip":        true,
	"setuptools": true,
	"wheel":      true,
	"distribute": true,
}

// filterPipBootstrap 过滤 pip/setuptools/wheel 等基础包。
func filterPipBootstrap(in []config.PipPackage, keep bool) []config.PipPackage {
	if keep {
		return in
	}
	out := make([]config.PipPackage, 0, len(in))
	for _, p := range in {
		if pipBootstrap[NormalizePipName(p.Name)] {
			continue
		}
		out = append(out, p)
	}
	return out
}

// filterPipOverlap 剔除同时由 conda 管理的包。
//
// conda 环境的 site-packages 同时出现在 conda list 与 pip list 里；若不去重，
// requirements.txt 会把 numpy/scipy 等再走一遍 pip，既慢又可能装成另一份 wheel。
func filterPipOverlap(in []config.PipPackage, condaNames map[string]bool) []config.PipPackage {
	if len(condaNames) == 0 {
		return in
	}
	out := make([]config.PipPackage, 0, len(in))
	for _, p := range in {
		if condaNames[NormalizePipName(p.Name)] {
			continue
		}
		out = append(out, p)
	}
	return out
}

// mergePip 合并 pip list 与 conda list 的 pypi 条目，按规范化名称去重。
func mergePip(primary, fallback []config.PipPackage) []config.PipPackage {
	out := make([]config.PipPackage, 0, len(primary)+len(fallback))
	seen := map[string]bool{}
	add := func(p config.PipPackage) {
		key := NormalizePipName(p.Name)
		if key == "" || seen[key] {
			return
		}
		seen[key] = true
		out = append(out, p)
	}
	for _, p := range primary {
		add(p)
	}
	for _, p := range fallback {
		add(p)
	}
	sort.SliceStable(out, func(i, j int) bool {
		return NormalizePipName(out[i].Name) < NormalizePipName(out[j].Name)
	})
	return out
}

// EnvironmentYAML 生成 conda create 用的 environment.yml。
//
// 不把 pip 包写进 environment.yml：pip 恢复由 Phase 2 单独执行，两者开关分开。
func EnvironmentYAML(env config.CondaEnv, profile *config.MirrorProfile) ([]byte, error) {
	channels := []string{}
	if profile != nil {
		channels = append(channels, profile.CondaChannels...)
	} else {
		seen := map[string]bool{}
		for _, p := range env.Packages {
			ch := strings.TrimSpace(p.Channel)
			if ch == "" || isDefaultChannel(ch) || strings.Contains(ch, "REDACTED") {
				continue
			}
			key := strings.ToLower(ch)
			if seen[key] {
				continue
			}
			seen[key] = true
			channels = append(channels, ch)
		}
	}
	deps := make([]string, 0, len(env.Packages)+2)
	if v := strings.TrimSpace(env.PythonVersion); v != "" {
		deps = append(deps, "python="+v)
	}
	seenPkg := map[string]bool{}
	for _, p := range env.Packages {
		if strings.EqualFold(p.Name, "python") && env.PythonVersion != "" {
			continue
		}
		if strings.TrimSpace(p.Name) == "" {
			continue
		}
		key := strings.ToLower(p.Name)
		if seenPkg[key] {
			continue
		}
		seenPkg[key] = true
		deps = append(deps, condaSpec(p))
	}
	if env.PipEnabled() && !seenPkg["pip"] {
		deps = append(deps, "pip")
	}

	doc := struct {
		Name         string   `yaml:"name"`
		Channels     []string `yaml:"channels,omitempty"`
		Dependencies []string `yaml:"dependencies"`
	}{
		Name:         env.Name,
		Channels:     channels,
		Dependencies: deps,
	}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, fmt.Errorf("生成 environment.yml 失败: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("生成 environment.yml 失败: %w", err)
	}
	return buf.Bytes(), nil
}

// condaSpec 生成 name=version[=build] 或 channel::name=...。
func condaSpec(p config.CondaPackage) string {
	spec := p.Name
	if p.Version != "" {
		spec += "=" + p.Version
	}
	if p.Build != "" {
		spec += "=" + p.Build
	}
	ch := strings.TrimSpace(p.Channel)
	if ch != "" && !isDefaultChannel(ch) && !strings.Contains(ch, "REDACTED") {
		spec = ch + "::" + spec
	}
	return spec
}

func isDefaultChannel(ch string) bool {
	switch strings.ToLower(strings.TrimSpace(ch)) {
	case "defaults", "pkgs/main", "pkgs/r", "main", "r", "msys2", "pypi":
		return true
	}
	return false
}

// RequirementsTXT 生成 pip install -r 用的清单。
func RequirementsTXT(env config.CondaEnv) []byte {
	lines := make([]string, 0, len(env.PipPackages)+1)
	lines = append(lines, "# generated by envlift; versions from conda env "+env.Name)
	seen := map[string]bool{}
	for _, p := range env.PipPackages {
		name := strings.TrimSpace(p.Name)
		if name == "" {
			continue
		}
		key := NormalizePipName(name)
		if seen[key] {
			continue
		}
		seen[key] = true
		if strings.TrimSpace(p.Version) == "" {
			lines = append(lines, name)
			continue
		}
		lines = append(lines, name+"=="+strings.TrimSpace(p.Version))
	}
	sort.Strings(lines[1:])
	return []byte(strings.Join(lines, "\n") + "\n")
}

// Condarc 生成临时 CONDARC。profile 为空时返回 nil，表示使用系统默认源。
func Condarc(profile *config.MirrorProfile) []byte {
	if profile == nil || len(profile.CondaChannels) == 0 {
		return nil
	}
	doc := struct {
		Channels        []string `yaml:"channels"`
		ShowChannelURLs bool     `yaml:"show_channel_urls"`
	}{
		Channels:        profile.CondaChannels,
		ShowChannelURLs: true,
	}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil
	}
	_ = enc.Close()
	return buf.Bytes()
}

// PipConfig 生成临时 pip.ini。只在显式配置了 profile 时生成。
func PipConfig(profile *config.MirrorProfile) []byte {
	if profile == nil || (profile.PipIndexURL == "" && len(profile.PipExtraIndex) == 0) {
		return nil
	}
	var b strings.Builder
	b.WriteString("[global]\n")
	if profile.PipIndexURL != "" {
		b.WriteString("index-url = " + profile.PipIndexURL + "\n")
	}
	if len(profile.PipExtraIndex) > 0 {
		b.WriteString("extra-index-url = " + strings.Join(profile.PipExtraIndex, " ") + "\n")
	}
	if len(profile.PipTrustedHost) > 0 {
		b.WriteString("trusted-host = " + strings.Join(profile.PipTrustedHost, " ") + "\n")
	}
	b.WriteString("disable-pip-version-check = true\n")
	return []byte(b.String())
}

// NormalizePipName 按 PEP 503 规范化包名（小写，-/_/. 等价）。
func NormalizePipName(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "_", "-")
	s = strings.ReplaceAll(s, ".", "-")
	for strings.Contains(s, "--") {
		s = strings.ReplaceAll(s, "--", "-")
	}
	return s
}

// CondaIndex 把 conda 包列表转成按名称索引。
func CondaIndex(pkgs []config.CondaPackage) map[string]config.CondaPackage {
	out := make(map[string]config.CondaPackage, len(pkgs))
	for _, p := range pkgs {
		out[strings.ToLower(strings.TrimSpace(p.Name))] = p
	}
	return out
}

// PipIndex 把 pip 包列表转成按规范化名称索引。
func PipIndex(pkgs []config.PipPackage) map[string]config.PipPackage {
	out := make(map[string]config.PipPackage, len(pkgs))
	for _, p := range pkgs {
		out[NormalizePipName(p.Name)] = p
	}
	return out
}

// CompareConda 返回缺失或版本/build 不符的包。
func CompareConda(want []config.CondaPackage, got []config.CondaPackage) []string {
	idx := CondaIndex(got)
	var out []string
	for _, w := range want {
		g, ok := idx[strings.ToLower(strings.TrimSpace(w.Name))]
		if !ok {
			out = append(out, fmt.Sprintf("%s（缺失）", w.Name))
			continue
		}
		if w.Version != "" && g.Version != w.Version {
			out = append(out, fmt.Sprintf("%s（期望 %s，实际 %s）", w.Name, w.Version, g.Version))
			continue
		}
		if w.Build != "" && g.Build != w.Build {
			out = append(out, fmt.Sprintf("%s（build 期望 %s，实际 %s）", w.Name, w.Build, g.Build))
		}
	}
	sort.Strings(out)
	return out
}

// ComparePip 返回缺失或版本不符的 pip 包。
func ComparePip(want []config.PipPackage, got []config.PipPackage) []string {
	idx := PipIndex(got)
	var out []string
	for _, w := range want {
		key := NormalizePipName(w.Name)
		g, ok := idx[key]
		if !ok {
			out = append(out, fmt.Sprintf("%s（缺失）", w.Name))
			continue
		}
		if w.Version != "" && g.Version != w.Version {
			out = append(out, fmt.Sprintf("%s（期望 %s，实际 %s）", w.Name, w.Version, g.Version))
		}
	}
	sort.Strings(out)
	return out
}
